"""Copy supplied Wassla vectors and rasterize platform sizes without redrawing.

Run from any directory with CairoSVG and Pillow installed. The untouched source
package lives in branding/wassla; only proportional sizing/padding is applied.
"""

from io import BytesIO
from pathlib import Path
import json
import re
import shutil

import cairosvg
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "branding/wassla"
WEB = ROOT / "web/assets/branding"
ADMIN = ROOT / "backend/monolith/apps/core/static/shiptrip/branding"
MOBILE = ROOT / "mobile/assets/branding"

# Android adaptive icon layers are 108 dp squares; launchers mask them to any
# shape that contains the central 66 dp circle. The W is drawn 56 dp wide so
# its outermost corners stay inside that circle.
ADAPTIVE_CANVAS = 108
ADAPTIVE_SAFE_DIAMETER = 66
ADAPTIVE_ART_WIDTH = 56
ANDROID_NS = "http://schemas.android.com/apk/res/android"


def raster(source, target, width, *, background=None):
    target.parent.mkdir(parents=True, exist_ok=True)
    cairosvg.svg2png(
        url=str(source), write_to=str(target), output_width=width,
        background_color=background,
    )


def _vector(body, *, aapt=False):
    namespaces = f'xmlns:android="{ANDROID_NS}"'
    if aapt:
        namespaces += ' xmlns:aapt="http://schemas.android.com/aapt"'
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"<!-- Generated by tools/branding/build_assets.py from branding/wassla. -->\n"
        f'<vector {namespaces}\n'
        f'    android:width="{ADAPTIVE_CANVAS}dp"\n'
        f'    android:height="{ADAPTIVE_CANVAS}dp"\n'
        f'    android:viewportWidth="{ADAPTIVE_CANVAS}"\n'
        f'    android:viewportHeight="{ADAPTIVE_CANVAS}">\n'
        f"{body}"
        "</vector>\n"
    )


def android_adaptive_icon(res):
    """The launcher icon for Android 8+: the supplied navy surface behind the
    supplied ivory-and-yellow W, and a one-colour W that Android 13+ tints for
    themed icons. Vectors, so every density is exact."""
    source = SOURCE / "02_app_icon/wassla-symbol-ivory.svg"
    svg = source.read_text()
    paths = re.findall(r'<path fill="(#[0-9A-Fa-f]{6})" d="([^"]+)"', svg)
    left_edge, top_edge, view_width, _ = (
        float(value) for value in re.search(r'viewBox="([^"]+)"', svg).group(1).split()
    )
    # Centre on the painted W, not on the viewBox and its padding.
    alpha = Image.open(BytesIO(cairosvg.svg2png(
        url=str(source), output_width=round(view_width),
    ))).getchannel("A")
    left, top, right, bottom = alpha.getbbox()
    scale = ADAPTIVE_ART_WIDTH / (right - left)
    half_diagonal = scale * ((right - left) ** 2 + (bottom - top) ** 2) ** 0.5 / 2
    assert half_diagonal <= ADAPTIVE_SAFE_DIAMETER / 2, "the W leaves the safe zone"
    middle = ADAPTIVE_CANVAS / 2
    translate_x = middle - scale * (left_edge + (left + right) / 2)
    translate_y = middle - scale * (top_edge + (top + bottom) / 2)

    def symbol(layers):
        drawn = "".join(
            f'        <path android:fillColor="{fill}" android:pathData="{data}" />\n'
            for fill, data in layers
        )
        return _vector(
            "    <group\n"
            f'        android:scaleX="{scale:.6f}"\n'
            f'        android:scaleY="{scale:.6f}"\n'
            f'        android:translateX="{translate_x:.4f}"\n'
            f'        android:translateY="{translate_y:.4f}">\n'
            f"{drawn}"
            "    </group>\n"
        )

    drawable = res / "drawable"
    (drawable / "ic_launcher_foreground.xml").write_text(symbol(paths))
    # One path, so the W and the sweep share an edge without a hairline seam
    # where two separately smoothed shapes meet.
    (drawable / "ic_launcher_monochrome.xml").write_text(
        symbol([("#FFFFFFFF", " ".join(data for _, data in paths))])
    )
    # The app icon's own navy surface (02_app_icon/wassla-app-icon-dark.svg).
    surface = re.search(
        r'<radialGradient id="navySurface" cx="([\d.]+)%" cy="([\d.]+)%" r="([\d.]+)%">'
        r'\s*<stop offset="0%" stop-color="(#[0-9A-Fa-f]{6})"/>'
        r'\s*<stop offset="100%" stop-color="(#[0-9A-Fa-f]{6})"/>',
        (SOURCE / "02_app_icon/wassla-app-icon-dark.svg").read_text(),
    )
    cx, cy, radius = (float(value) * ADAPTIVE_CANVAS / 100 for value in surface.groups()[:3])
    (drawable / "ic_launcher_background.xml").write_text(_vector(
        f'    <path android:pathData="M0,0h{ADAPTIVE_CANVAS}v{ADAPTIVE_CANVAS}h-{ADAPTIVE_CANVAS}z">\n'
        '        <aapt:attr name="android:fillColor">\n'
        "            <gradient\n"
        '                android:type="radial"\n'
        f'                android:centerX="{cx:.2f}"\n'
        f'                android:centerY="{cy:.2f}"\n'
        f'                android:gradientRadius="{radius:.2f}"\n'
        f'                android:startColor="{surface.group(4)}"\n'
        f'                android:endColor="{surface.group(5)}" />\n'
        "        </aapt:attr>\n"
        "    </path>\n",
        aapt=True,
    ))
    anydpi = res / "mipmap-anydpi-v26"
    anydpi.mkdir(exist_ok=True)
    (anydpi / "ic_launcher.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f'<adaptive-icon xmlns:android="{ANDROID_NS}">\n'
        '    <background android:drawable="@drawable/ic_launcher_background" />\n'
        '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
        '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n'
        "</adaptive-icon>\n"
    )


def build():
    for folder in (WEB, ADMIN, MOBILE):
        folder.mkdir(parents=True, exist_ok=True)
    for variant in ("navy", "ivory"):
        name = f"wassla-primary-{variant}"
        source = SOURCE / f"01_logos/{name}.svg"
        for folder in (WEB, ADMIN):
            shutil.copyfile(source, folder / f"{name}.svg")
        # Four physical pixels per logical pixel on the largest mobile mark.
        raster(source, MOBILE / f"{name}.png", 960)
        name = f"wassla-symbol-{variant}"
        source = SOURCE / f"02_app_icon/{name}.svg"
        raster(source, MOBILE / f"{name}.png", 192)
    # An opaque supplied banner remains legible when email clients invert paper.
    raster(SOURCE / "01_logos/wassla-on-ivory.svg", WEB / "wassla-email.png", 720)
    favicon = SOURCE / "02_app_icon/favicon.svg"
    shutil.copyfile(favicon, ROOT / "web/assets/favicon.svg")
    shutil.copyfile(favicon, ADMIN / "favicon.svg")
    icon_source = SOURCE / "02_app_icon/wassla-app-icon-dark.svg"
    icon = Image.open(BytesIO(cairosvg.svg2png(url=str(icon_source), output_width=1024)))
    # iOS store icons must be opaque; retain the supplied navy beneath corners.
    opaque = Image.new("RGBA", icon.size, "#042D49")
    opaque.alpha_composite(icon.convert("RGBA"))
    icon = opaque.convert("RGB")
    icon.save(ROOT / "web/favicon.ico", sizes=[(16, 16), (32, 32), (48, 48)])
    res = ROOT / "mobile/android/app/src/main/res"
    # The legacy square icon, for Android 7; Android 8+ uses the adaptive one.
    for density, size in {"mdpi":48,"hdpi":72,"xhdpi":96,"xxhdpi":144,"xxxhdpi":192}.items():
        icon.resize((size, size), Image.Resampling.LANCZOS).save(res / f"mipmap-{density}/ic_launcher.png")
    icons = ROOT / "mobile/ios/Runner/Assets.xcassets/AppIcon.appiconset"
    for entry in json.loads((icons / "Contents.json").read_text())["images"]:
        size = round(float(entry["size"].split("x")[0]) * float(entry["scale"].rstrip("x")))
        icon.resize((size, size), Image.Resampling.LANCZOS).save(icons / entry["filename"])
    launch = ROOT / "mobile/ios/Runner/Assets.xcassets/LaunchImage.imageset"
    for scale in (1, 2, 3):
        suffix = "" if scale == 1 else f"@{scale}x"
        for variant in ("navy", "ivory"):
            filename = f"LaunchImage{suffix}.png" if variant == "navy" else f"LaunchImage-dark{suffix}.png"
            raster(SOURCE / f"01_logos/wassla-primary-{variant}.svg", launch / filename, 240 * scale)
    # Native Android launch bitmap at a fixed logical size on all densities.
    for variant, folder in (("navy", "drawable-nodpi"), ("ivory", "drawable-night-nodpi")):
        raster(SOURCE / f"01_logos/wassla-primary-{variant}.svg", res / folder / "wassla_launch.png", 960)
    # Android 12 masks the launch icon; pad the supplied transparent symbol
    # inside its safe central region rather than letting the OS crop the W.
    symbol = Image.open(BytesIO(cairosvg.svg2png(
        url=str(SOURCE / "02_app_icon/wassla-symbol-ivory.svg"), output_width=384,
    )))
    padded = Image.new("RGBA", (768, 768))
    padded.alpha_composite(symbol, ((768-symbol.width)//2, (768-symbol.height)//2))
    padded.save(res / "drawable-nodpi/wassla_splash_icon.png")
    android_adaptive_icon(res)


if __name__ == "__main__":
    build()
